// Offline extraction: reads real glyph outlines from the bold display font
// and writes simplified polygon contours (outer boundary + any enclosed
// counters/holes) into lib/fire-game/letterform-data.ts as plain data.
// Neither opentype.js nor the font package ships to the actual site — both
// are devDependencies, only ever used here, at dev time.
//
// Run with: node scripts/extract-letterforms.mjs   (from the project root)
import opentype from "opentype.js";
import fs from "fs";

const FONT_PATH =
  "node_modules/@fontsource/archivo-black/files/archivo-black-latin-400-normal.woff";
const LETTERS = ["A", "s", "t", "r", "a", "p", "e"];
const CURVE_SAMPLES = 14; // points per bezier segment before simplification
const SIMPLIFY_EPS = 7; // font units (unitsPerEm=1000, cap height ~688)

function flatten(path) {
  const contours = [];
  let current = null;
  let cx = 0,
    cy = 0,
    start = null;
  for (const c of path.commands) {
    if (c.type === "M") {
      if (current && current.length) contours.push(current);
      current = [{ x: c.x, y: c.y }];
      cx = c.x;
      cy = c.y;
      start = { x: c.x, y: c.y };
    } else if (c.type === "L") {
      current.push({ x: c.x, y: c.y });
      cx = c.x;
      cy = c.y;
    } else if (c.type === "Q") {
      for (let i = 1; i <= CURVE_SAMPLES; i++) {
        const t = i / CURVE_SAMPLES;
        const mt = 1 - t;
        const x = mt * mt * cx + 2 * mt * t * c.x1 + t * t * c.x;
        const y = mt * mt * cy + 2 * mt * t * c.y1 + t * t * c.y;
        current.push({ x, y });
      }
      cx = c.x;
      cy = c.y;
    } else if (c.type === "C") {
      for (let i = 1; i <= CURVE_SAMPLES; i++) {
        const t = i / CURVE_SAMPLES;
        const mt = 1 - t;
        const x = mt * mt * mt * cx + 3 * mt * mt * t * c.x1 + 3 * mt * t * t * c.x2 + t * t * t * c.x;
        const y = mt * mt * mt * cy + 3 * mt * mt * t * c.y1 + 3 * mt * t * t * c.y2 + t * t * t * c.y;
        current.push({ x, y });
      }
      cx = c.x;
      cy = c.y;
    } else if (c.type === "Z") {
      if (start) current.push({ x: start.x, y: start.y });
    }
  }
  if (current && current.length) contours.push(current);
  return contours;
}

function perpDist(p, a, b) {
  const dx = b.x - a.x,
    dy = b.y - a.y;
  const len = Math.hypot(dx, dy) || 1e-6;
  const t = ((p.x - a.x) * dx + (p.y - a.y) * dy) / (len * len);
  const px = a.x + t * dx,
    py = a.y + t * dy;
  return Math.hypot(p.x - px, p.y - py);
}
function simplify(points, eps) {
  if (points.length < 3) return points;
  let maxD = 0,
    idx = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpDist(points[i], points[0], points[points.length - 1]);
    if (d > maxD) {
      maxD = d;
      idx = i;
    }
  }
  if (maxD > eps) {
    const left = simplify(points.slice(0, idx + 1), eps);
    const right = simplify(points.slice(idx), eps);
    return left.slice(0, -1).concat(right);
  }
  return [points[0], points[points.length - 1]];
}

function signedArea(pts) {
  let a = 0;
  for (let i = 0; i < pts.length; i++) {
    const p1 = pts[i],
      p2 = pts[(i + 1) % pts.length];
    a += p1.x * p2.y - p2.x * p1.y;
  }
  return a / 2;
}

const font = opentype.parse(
  (() => {
    const buf = fs.readFileSync(FONT_PATH);
    return buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
  })()
);

const out = {};
for (const ch of LETTERS) {
  const glyph = font.charToGlyph(ch);
  const path = glyph.getPath(0, 0, 1000);
  const rawContours = flatten(path);
  const simplified = rawContours.map((c) => simplify(c, SIMPLIFY_EPS));
  const withArea = simplified.map((c) => ({ pts: c, area: Math.abs(signedArea(c)) }));
  withArea.sort((a, b) => b.area - a.area);
  out[ch] = {
    advance: glyph.advanceWidth,
    // First contour (largest area) = outer boundary. Any remaining = holes/counters.
    contours: withArea.map((c, i) => ({
      kind: i === 0 ? "outer" : "hole",
      points: c.pts.map((p) => [Math.round(p.x), Math.round(p.y)]),
    })),
  };
  console.log(ch, "contours:", withArea.map((c) => c.pts.length).join(","));
}

const tsOut =
  `// Auto-generated by scripts/extract-letterforms.mjs from Archivo Black\n` +
  `// (bold display font). Coordinates are raw font units (unitsPerEm=1000,\n` +
  `// baseline y=0, upward is negative y). Do not hand-edit — re-run the\n` +
  `// script if the font or letter set changes, then re-check lib/fire-game/\n` +
  `// level.ts's opening cuts against the new point indices (they will have\n` +
  `// shifted).\n` +
  `import type { RawGlyph } from "./letterform-types";\n\n` +
  `export const LETTERFORMS: Record<string, RawGlyph> = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync("lib/fire-game/letterform-data.ts", tsOut);
console.log("wrote lib/fire-game/letterform-data.ts");
